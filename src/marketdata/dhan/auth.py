"""
The DhanHQ access-token lifecycle (verified against dhanhq.co/docs/v2/authentication/).

Three ways in, tried in this order:

1. **A token file** written by ``scripts/dhan_oauth_token.py`` (the OAuth consent flow for
   accounts with an app key/secret): ``{"access_token": ..., "expiry": ...}`` under the
   gitignored state directory by default.
2. **A supplied token** (``DHAN_ACCESS_TOKEN``), e.g. one generated by hand in Dhan Web.
3. **TOTP generation** (Dhan's documented "Method 2" for individual traders):
   ``POST https://auth.dhan.co/app/generateAccessToken?dhanClientId=..&pin=..&totp=..`` where
   ``pin`` is the account's 6-digit Dhan PIN and ``totp`` a fresh RFC 6238 code from the TOTP
   seed the operator copied out of Dhan Web (My Profile > DhanHQ Trading APIs > Setup TOTP).

Access tokens are valid 24 h; a cached token is regenerated shortly before it expires, and a
rejected one (HTTP 401/403) is dropped so the next call falls through to the next method that
is configured. A token minted over TOTP is written to the token file, because Dhan allows only
**one generation per two minutes** and answers an early retry with an HTTP 200 error body, not a
4xx - so a restart that re-minted would fail outright. An API key/secret is *not* an access
token: it only identifies the application in the consent flow, which needs an interactive
browser login (see :mod:`.oauth`).

Nothing secret is ever logged: failures quote only the HTTP status and a redacted fragment of
the response body, and no token, PIN or TOTP code ever appears in a message or in the token
file's path handling beyond writing the file itself.
"""

from __future__ import annotations

import asyncio
import json
import os
from collections.abc import Callable
from dataclasses import dataclass
from datetime import datetime, timedelta
from pathlib import Path
from typing import Any

import httpx2
from pydantic import SecretStr

from src.config.errors import ConfigError
from src.marketdata.dhan.errors import DhanAuthError
from src.marketdata.dhan.totp import totp_code
from src.ops.logging_config import redact
from src.utils.market_time import IST, now_ist

AUTH_BASE_URL = "https://auth.dhan.co"
TOKEN_PATH = "/app/generateAccessToken"
TOKEN_FILE_NAME = "dhan_token.json"

# Dhan documents a 24 h validity; a token whose expiry cannot be parsed is refreshed after half
# of that, so an unparsable ``expiryTime`` can never leave us holding a dead token.
DOCUMENTED_VALIDITY = timedelta(hours=24)
UNPARSED_EXPIRY_REFRESH = DOCUMENTED_VALIDITY / 2
EXPIRY_FORMATS = (
    "%Y-%m-%dT%H:%M:%S.%f",
    "%Y-%m-%dT%H:%M:%S",
    "%Y-%m-%d %H:%M:%S.%f",
    "%Y-%m-%d %H:%M:%S",
)


@dataclass(frozen=True, slots=True)
class DhanToken:
    access_token: str
    expiry: datetime


def parse_expiry(text: str, now: datetime) -> datetime:
    """``expiryTime`` as an aware IST instant; half the documented validity when unparsable."""
    for fmt in EXPIRY_FORMATS:
        try:
            naive = datetime.strptime(text.strip(), fmt)
        except ValueError:
            continue
        moment = naive if naive.tzinfo else naive.replace(tzinfo=IST)
        return moment.astimezone(IST)
    iso = text.strip()
    if iso.endswith(("Z", "z")):
        iso = iso[:-1] + "+00:00"
    try:
        return datetime.fromisoformat(iso).astimezone(IST)
    except ValueError:
        return now + UNPARSED_EXPIRY_REFRESH


def failure_reason(body: Any) -> str | None:
    """Why Dhan refused, from an HTTP 200 error body: ``{"message": ...}`` or
    ``{"status": "error", "remarks": {"errorMessage": ...}}``.

    The auth service reports a rejected PIN, a reused TOTP code and the two-minute generation
    limit all as HTTP 200, so the body is the only place the reason lives.
    """
    if not isinstance(body, dict):
        return None
    message = body.get("message")
    if isinstance(message, str) and message.strip():
        return message.strip()
    remarks = body.get("remarks")
    if isinstance(remarks, dict):
        for key in ("errorMessage", "message", "errorCode"):
            value = remarks.get(key)
            if isinstance(value, str) and value.strip():
                return value.strip()
    status = body.get("status")
    return f"status={status}" if isinstance(status, str) and status.strip() else None


def read_token_file(path: Path, *, now: datetime) -> DhanToken | None:
    """The stored token if the file exists, parses, and has not expired."""
    try:
        body: Any = json.loads(path.read_text(encoding="utf-8"))
        token = str(body["access_token"])
        expiry = parse_expiry(str(body.get("expiry") or ""), now)
    except (OSError, ValueError, KeyError, TypeError):
        return None
    return DhanToken(token, expiry) if expiry > now else None


def write_token_file(path: Path, token: DhanToken) -> None:
    """Store a minted token under the gitignored state directory, owner-readable where possible."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps({"access_token": token.access_token, "expiry": token.expiry.isoformat()}),
        encoding="utf-8",
    )
    try:
        os.chmod(path, 0o600)
    except OSError:
        pass  # Windows ACLs: the file still lives under the gitignored var/ tree


class DhanAuth:
    """Holds at most one live token and regenerates it just before it expires."""

    def __init__(
        self,
        *,
        client_id: str,
        pin: SecretStr | None = None,
        totp_secret: SecretStr | None = None,
        access_token: SecretStr | None = None,
        token_file: Path | None = None,
        client: httpx2.AsyncClient | None = None,
        base_url: str = AUTH_BASE_URL,
        now: Callable[[], datetime] = now_ist,
        refresh_margin_s: float = 300.0,
    ) -> None:
        if not client_id:
            raise ConfigError("DHAN_CLIENT_ID is required when MARKET_DATA_PROVIDER=dhan")
        self._client_id = client_id
        self._pin = pin.get_secret_value() if pin else None
        self._totp_secret = totp_secret.get_secret_value() if totp_secret else None
        self._static = access_token.get_secret_value() if access_token else None
        self._token_file = token_file
        if (
            self._token_file is None
            and self._static is None
            and (self._pin is None or self._totp_secret is None)
        ):
            raise ConfigError(
                "MARKET_DATA_PROVIDER=dhan needs a way to get an access token: run "
                "scripts/dhan_oauth_token.py (uses DHAN_API_KEY/DHAN_API_SECRET and writes a "
                "token file), or set DHAN_ACCESS_TOKEN, or set both DHAN_PIN and "
                "DHAN_TOTP_SECRET so a token can be generated headlessly. The TOTP secret is "
                "shown once, when you choose 'Setup TOTP' in Dhan Web."
            )
        self._client = client
        self._base_url = base_url.rstrip("/")
        self._now = now
        self._margin_s = refresh_margin_s
        self._token: DhanToken | None = None
        self._dead_file_token: str | None = None
        self._dead_static = False
        self._lock = asyncio.Lock()

    @property
    def client_id(self) -> str:
        return self._client_id

    @property
    def method(self) -> str:
        """How a token is obtained, for the readiness check: never a secret."""
        ways = []
        if self._token_file is not None:
            ways.append(f"token file {self._token_file.name}")
        if self._static is not None:
            ways.append("DHAN_ACCESS_TOKEN")
        if self._pin is not None and self._totp_secret is not None:
            ways.append("DHAN_PIN + DHAN_TOTP_SECRET")
        return " -> ".join(ways) if ways else "none configured"

    def invalidate(self) -> None:
        """Drop the cached token after a 401/403 and remember it was rejected, so a stale token
        file or environment token is not replayed."""
        if self._token is not None:
            self.mark_rejected(self._token.access_token)
        self._token = None

    async def token(self) -> str:
        async with self._lock:
            now = self._now()
            if self._token is None or (self._token.expiry - now).total_seconds() < self._margin_s:
                self._token = await self._issue(now)
            return self._token.access_token

    async def _issue(self, now: datetime) -> DhanToken:
        if self._token_file is not None:
            stored = read_token_file(self._token_file, now=now)
            if stored is not None and stored.access_token != self._dead_file_token:
                return stored
        if self._static is not None and not self._dead_static:
            # A supplied token's age is unknown: assume half the documented validity.
            return DhanToken(self._static, now + UNPARSED_EXPIRY_REFRESH)
        if self._totp_secret is None or self._pin is None:
            raise DhanAuthError(
                f"every configured Dhan token source was rejected or is missing: {self.method}",
                status=None,
            )
        return await self._generate_with_totp(now)

    async def _generate_with_totp(self, now: datetime) -> DhanToken:
        if self._totp_secret is None:
            raise DhanAuthError("Dhan TOTP secret is not configured")
        code = totp_code(self._totp_secret, at=now.timestamp())
        client = self._client if self._client is not None else httpx2.AsyncClient(timeout=20.0)
        try:
            response = await client.post(
                f"{self._base_url}{TOKEN_PATH}",
                params={"dhanClientId": self._client_id, "pin": self._pin, "totp": code},
            )
        except httpx2.HTTPError as exc:
            raise DhanAuthError(
                f"cannot reach the Dhan auth service: {type(exc).__name__}"
            ) from exc
        finally:
            if self._client is None:
                await client.aclose()
        if response.status_code in (401, 403):
            raise DhanAuthError(
                "Dhan rejected the client id, PIN or TOTP code (HTTP "
                f"{response.status_code}); re-check DHAN_CLIENT_ID, DHAN_PIN and DHAN_TOTP_SECRET "
                "in Dhan Web > DhanHQ Trading APIs",
                status=response.status_code,
            )
        if response.status_code >= 400:
            raise DhanAuthError(
                f"token generation failed (HTTP {response.status_code}): "
                f"{redact(response.text[:300])}",
                status=response.status_code,
            )
        try:
            body: Any = response.json()
        except ValueError as exc:
            raise DhanAuthError(
                f"token generation returned no JSON (HTTP {response.status_code}): "
                f"{redact(response.text[:200])}",
                status=response.status_code,
            ) from exc
        access_token = body.get("accessToken") if isinstance(body, dict) else None
        if not isinstance(access_token, str) or not access_token:
            reason = failure_reason(body) or redact(response.text[:200]) or "no reason given"
            raise DhanAuthError(
                f"token generation was refused (HTTP {response.status_code}): {redact(reason)}",
                status=response.status_code,
            )
        token = DhanToken(access_token, parse_expiry(str(body.get("expiryTime") or ""), now))
        self._store(token)
        return token

    def _store(self, token: DhanToken) -> None:
        """Persist a freshly minted token so the next process reuses it instead of re-minting:
        Dhan allows one generation per two minutes, and an early retry fails the whole start."""
        if self._token_file is None:
            return
        try:
            write_token_file(self._token_file, token)
        except OSError:
            pass  # the in-memory token still works; only the next restart has to mint again

    def mark_rejected(self, token: str) -> None:
        """Remember a token Dhan rejected, so a stale token file or env token is not retried."""
        if self._static == token:
            self._dead_static = True
        if self._token_file is not None:
            self._dead_file_token = token
        self._token = None
